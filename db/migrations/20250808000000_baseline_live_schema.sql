-- New account: profile, wallet, and a babalawos row when signing up as one.
-- Replaced (with role hardening) in 20261108000100.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  wanted public.user_role := CASE
    WHEN NEW.raw_user_meta_data->>'role' = 'babalawo' THEN 'babalawo'::public.user_role
    ELSE 'user'::public.user_role END;   -- never 'admin' from signup
BEGIN
  INSERT INTO public.profiles (id, email, full_name, role)
  VALUES (NEW.id, COALESCE(NEW.email, ''), COALESCE(NEW.raw_user_meta_data->>'full_name', ''), wanted);
  INSERT INTO public.wallets (user_id) VALUES (NEW.id) ON CONFLICT (user_id) DO NOTHING;
  IF wanted = 'babalawo' THEN
    INSERT INTO public.babalawos (user_id) VALUES (NEW.id) ON CONFLICT (user_id) DO NOTHING;
    INSERT INTO public.babalawo_wallets (babalawo_id) VALUES (NEW.id) ON CONFLICT (babalawo_id) DO NOTHING;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Keep babalawos.rating / total_sessions in step with approved reviews and
-- completed sessions.
CREATE OR REPLACE FUNCTION public.update_babalawo_rating()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  target uuid := COALESCE(NEW.babalawo_id, OLD.babalawo_id);
BEGIN
  IF target IS NULL THEN RETURN NULL; END IF;
  UPDATE public.babalawos b SET
    rating = COALESCE((SELECT avg(r.rating)::real FROM public.reviews r
                       WHERE r.babalawo_id = target AND r.is_approved), 0),
    total_sessions = (SELECT count(*) FROM public.sessions s
                      WHERE s.babalawo_id = target AND s.status = 'completed')
  WHERE b.user_id = target;
  RETURN NULL;
END $$;

CREATE TRIGGER reviews_update_rating
  AFTER INSERT OR UPDATE OR DELETE ON public.reviews
  FOR EACH ROW EXECUTE FUNCTION public.update_babalawo_rating();
CREATE TRIGGER sessions_update_rating
  AFTER UPDATE OF status ON public.sessions
  FOR EACH ROW EXECUTE FUNCTION public.update_babalawo_rating();

-- Public directory of verified, active Babalawos. id is the Babalawo's user id.
CREATE OR REPLACE FUNCTION public.get_public_babalawos()
RETURNS TABLE(id uuid, full_name text, avatar_url text, specialties text[], experience_years integer,
              hourly_rate numeric, bio text, verification_status text, rating real, total_sessions integer,
              languages text[], timezone text, is_active boolean, is_featured boolean, current_status text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT b.user_id, p.full_name, COALESCE(b.profile_picture_url, p.avatar_url), b.specialties,
         b.experience_years, b.hourly_rate, b.bio,
         CASE WHEN b.is_verified THEN 'approved' ELSE 'pending' END,
         b.rating, b.total_sessions, b.languages, b.timezone, b.is_active,
         COALESCE(b.is_featured, false), COALESCE(b.current_status, 'offline')
  FROM public.babalawos b
  JOIN public.profiles p ON p.id = b.user_id
  WHERE b.is_verified AND COALESCE(b.is_active, true)
$$;

CREATE OR REPLACE FUNCTION public.get_babalawo_details_by_ids(p_ids uuid[])
RETURNS TABLE(id uuid, full_name text, avatar_url text, specialties text[])
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT p.id, p.full_name, COALESCE(b.profile_picture_url, p.avatar_url), b.specialties
  FROM public.profiles p
  LEFT JOIN public.babalawos b ON b.user_id = p.id
  WHERE p.id = ANY(p_ids)
$$;

-- Earnings dashboard for one Babalawo (their own, or any for an admin).
CREATE OR REPLACE FUNCTION public.get_babalawo_earnings_stats(p_babalawo_id uuid)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_all_time numeric; v_available numeric; v_pending numeric;
  v_requests jsonb; v_payouts jsonb; v_rates jsonb;
BEGIN
  IF auth.uid() IS DISTINCT FROM p_babalawo_id AND NOT public.is_admin() THEN
    RAISE EXCEPTION 'not allowed' USING ERRCODE = '42501';
  END IF;

  SELECT COALESCE(sum(COALESCE(pay.babalawo_amount, s.amount)), 0) INTO v_all_time
  FROM public.sessions s
  LEFT JOIN public.payments pay ON pay.session_id = s.id AND pay.status IN ('paid', 'completed', 'successful')
  WHERE s.babalawo_id = p_babalawo_id AND s.status = 'completed';

  SELECT COALESCE(available_balance, 0) INTO v_available
  FROM public.babalawo_wallets WHERE babalawo_id = p_babalawo_id;

  SELECT COALESCE(sum(amount), 0) INTO v_pending
  FROM public.withdrawal_requests WHERE babalawo_id = p_babalawo_id AND status IN ('pending', 'approved');

  SELECT COALESCE(jsonb_agg(jsonb_build_object('id', id, 'amount', amount, 'status', status,
         'created_at', created_at) ORDER BY created_at DESC), '[]') INTO v_requests
  FROM public.withdrawal_requests WHERE babalawo_id = p_babalawo_id;

  SELECT COALESCE(jsonb_agg(jsonb_build_object('id', id, 'amount', amount, 'method', method,
         'reference', reference, 'status', status, 'created_at', created_at) ORDER BY created_at DESC), '[]')
    INTO v_payouts
  FROM public.payouts WHERE babalawo_id = p_babalawo_id;

  SELECT jsonb_build_object(
    'babalawo_percent', COALESCE(b.commission_babalawo_percent,
      (SELECT setting_value::numeric FROM public.admin_settings WHERE setting_key = 'babalawo_commission_percent'), 80),
    'platform_percent', COALESCE(b.commission_platform_percent,
      (SELECT setting_value::numeric FROM public.admin_settings WHERE setting_key = 'platform_commission_percent'), 20))
    INTO v_rates
  FROM public.babalawos b WHERE b.user_id = p_babalawo_id;

  RETURN jsonb_build_object(
    'all_time_earnings', v_all_time,
    'available_balance', COALESCE(v_available, 0),
    'pending_payouts', v_pending,
    'withdrawal_requests', v_requests,
    'payout_history', v_payouts,
    'commission_rates', COALESCE(v_rates, '{}'::jsonb));
END $$;

-- Wallet movement. Server-only: browsers must never move money themselves.
-- (On Supabase this was callable by any signed-in user; the payments
-- migration 20261108000200 replaces it with an escrow ledger.)
CREATE OR REPLACE FUNCTION public.update_wallet_balance(
  p_user_id uuid, p_amount numeric, p_transaction_type text, p_transaction_source text,
  p_payment_gateway text DEFAULT NULL, p_payment_reference text DEFAULT NULL,
  p_session_id text DEFAULT NULL, p_description text DEFAULT NULL)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_wallet uuid; v_tx uuid;
BEGIN
  IF p_amount IS NULL OR p_amount <= 0 THEN RAISE EXCEPTION 'amount must be positive'; END IF;
  IF p_transaction_type NOT IN ('credit', 'debit') THEN RAISE EXCEPTION 'invalid transaction type'; END IF;

  INSERT INTO public.wallets (user_id) VALUES (p_user_id) ON CONFLICT (user_id) DO NOTHING;
  SELECT id INTO v_wallet FROM public.wallets WHERE user_id = p_user_id FOR UPDATE;

  UPDATE public.wallets
     SET balance = balance + CASE WHEN p_transaction_type = 'credit' THEN p_amount ELSE -p_amount END
   WHERE id = v_wallet;   -- CHECK (balance >= 0) rejects overdrafts

  INSERT INTO public.wallet_transactions (wallet_id, user_id, amount, transaction_type, transaction_source,
    payment_gateway, payment_reference, session_id, description)
  VALUES (v_wallet, p_user_id, p_amount, p_transaction_type, p_transaction_source,
    p_payment_gateway, p_payment_reference, p_session_id, p_description)
  RETURNING id INTO v_tx;
  RETURN v_tx;
END $$;
REVOKE EXECUTE ON FUNCTION public.update_wallet_balance(uuid, numeric, text, text, text, text, text, text)
  FROM PUBLIC, anon, authenticated;

-- Mark sessions completed once they are well past their end time.
CREATE OR REPLACE FUNCTION public.auto_complete_sessions()
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  UPDATE public.sessions
     SET status = 'completed'
   WHERE status IN ('confirmed', 'in_progress')
     AND (session_date + end_time) AT TIME ZONE COALESCE(user_timezone, 'Africa/Lagos') < now() - interval '2 hours'
$$;
REVOKE EXECUTE ON FUNCTION public.auto_complete_sessions() FROM PUBLIC, anon, authenticated;

