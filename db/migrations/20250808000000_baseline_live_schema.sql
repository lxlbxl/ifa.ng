-- Baseline: the IFA.ng schema as it ran on Supabase, rebuilt for plain Postgres.
--
-- Why this file exists: the old supabase/migrations history does not replay on
-- an empty database (tables were changed in the Supabase dashboard and never
-- written back), and the live Supabase project is no longer accessible. This
-- baseline was rebuilt from the last Supabase-generated type file
-- (src/integrations/supabase/types.ts, generated 2025-08-08 from the live
-- database), with SQL types, defaults and functions taken from the old
-- migrations. server/test/schema.test.ts checks every table, column, nullability,
-- enum and function in that type file against the result.
--
-- Identity conventions used everywhere:
--   * every person is an auth.users row; profiles.id = auth.users.id
--   * *.user_id and *.babalawo_id that hold a person are uuid = auth.users.id
--   * babalawos.id is a bigint row id; babalawos.user_id is the person
--     (ritual_reminders.babalawo_id is the one column that points at babalawos.id)
--   * sessions.id is bigint; every session_id is bigint
--
-- Requires db/compat/000_supabase_compat.sql (roles, auth.users, auth.uid()).

